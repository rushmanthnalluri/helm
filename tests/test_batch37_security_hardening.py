"""tests/test_batch37_security_hardening.py - Batch 37 Formal Security Hardening Acceptance Suite.

Directives Covered:
1. Signed Approval Blobs (Store Evidence, Not a Verdict):
   - approved_actions SQLite table and supervisor cache store and verify the Signed Approval Blob.
   - consume_approved_action independently verifies Ed25519 signature against enrolled public keys in .helm_device_keys.json.
   - Unverified rows, missing signatures, forged signatures, or tampered args_hash fail closed.
2. Recovery CLI Hardening via Windows UAC Secure Desktop:
   - helm.py checks ctypes.windll.shell32.IsUserAnAdmin().
   - If not elevated, requests Windows UAC Secure Desktop elevation via ShellExecuteW(runas).
   - If elevation is cancelled or unavailable, fails closed without modifying recovery tokens.
3. Hardened UIA Domain Resolution:
   - get_browser_active_domain scopes search strictly to descendants of top-level window hwnd.
   - Desktop root fallback eliminated (never matches address bars of background windows or web page inputs).
   - Filters browser chrome toolbar controls specifically (Chrome_OmniboxView, OmniboxViewViews, addressEditBox, urlbar-input).
4. Actuator-Level TOCTOU Window Switching Defense:
   - SupervisorActuator.execute_actuator re-resolves OS foreground window and domain immediately before executing.
   - Aborts with CompleteMediationBreachError if active foreground process or domain switched away from envelope.
5. Exact VK Canonicalizer Prose Separation & System Hotkey Blocks:
   - Numeric decimal strings in free-form prose (e.g. typing "13" or "80") never trigger Enter or P VK events.
   - Blocks dangerous system chords: Win+R, Win+X, Alt+F4, Ctrl+Shift+Esc, Ctrl+Alt+Del in policy envelope and actuator.
6. Window Focus Loss Modifier Clearing:
   - Low-level keyboard hook callback in app.py resets _physical_ctrl_down and _physical_alt_down on WM_KILLFOCUS (0x0008).
"""

