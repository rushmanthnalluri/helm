    def test_1_signed_approval_evidence_verification_and_unverified_sqlite_row_rejection(self):
        """Directive 1: Supervisor stores and verifies cryptographic evidence blobs; unverified rows fail closed."""
        priv_pem, pub_pem = enroll_test_device("primary_phone")
        caller_id = "worker_b37"
        tool_name = "helm_set_clipboard"
        args = {"text": "classified_content"}
        clean_args = json.dumps(args, sort_keys=True, separators=(',', ':'))
        args_hash = hashlib.sha256(clean_args.encode('utf-8')).hexdigest()
        epoch = taint_tracker.get_taint_epoch()

        # Step 1: Valid signed approval blob generated by mobile hardware enclave
        signed_blob = mint_test_action_approval(
            priv_pem, tool_name, args_hash, device_id="primary_phone", taint_epoch=epoch
        )
        signed_blob["caller_id"] = caller_id
        signed_blob["tool_name"] = tool_name
        signed_blob["args_hash"] = args_hash

        sup = helm_supervisor.PolicySupervisor()
        sup.record_approved_action(caller_id, tool_name, args_hash, epoch, ttl=60.0, signed_blob=signed_blob)

        # Verified evidence: consumption succeeds
        consumed = sup.consume_approved_action(caller_id, tool_name, args_hash, epoch)
        self.assertTrue(consumed, "Valid signed evidence blob failed consumption")

        # Single-use: replay consumption fails
        consumed_replay = sup.consume_approved_action(caller_id, tool_name, args_hash, epoch)
        self.assertFalse(consumed_replay, "Replay attack succeeded on consumed approval")

        # Step 2: Unsigned row inserted directly into SQLite table by same-user process (attack simulation)
        with db_utils.get_db() as conn:
            helm_supervisor._init_approved_actions_table(conn)
            conn.execute("""
                INSERT INTO approved_actions (caller_id, tool, args_hash, taint_epoch, expiry, consumed, signature_blob)
                VALUES (?, ?, ?, ?, ?, 0, ?)
            """, (caller_id, tool_name, args_hash.lower(), epoch, time.time() + 60.0, json.dumps({"forged": True})))
            conn.commit()

        # Supervisor MUST reject unsigned row (fails closed)
        consumed_unsigned = sup.consume_approved_action(caller_id, tool_name, args_hash, epoch)
        self.assertFalse(consumed_unsigned, "CRITICAL: Supervisor accepted unsigned SQLite row without cryptographic evidence!")

        # Step 3: Forged signature blob (tampered args_hash) MUST fail closed
        tampered_blob = dict(signed_blob)
        tampered_blob["args_hash"] = "ffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff"
        sup.record_approved_action(caller_id, tool_name, args_hash, epoch, ttl=60.0, signed_blob=tampered_blob)
        consumed_forged = sup.consume_approved_action(caller_id, tool_name, args_hash, epoch)
        self.assertFalse(consumed_forged, "Supervisor accepted tampered signature blob!")

    def test_2_recovery_cli_requires_uac_secure_desktop_elevation(self):
        """Directive 2: Recovery CLI requires administrative elevation and refuses unhardened script elevation."""
        import helm

        # Non-elevated invocation fails closed immediately to prevent privilege escalation via user-writable scripts
        with patch.object(sys, "argv", ["helm.py", "--pairing-unlock"]):
            with patch.object(sys.stdin, "isatty", return_value=True):
                with patch("ctypes.windll.shell32.IsUserAnAdmin", return_value=0):
                    with patch("builtins.print") as mock_print:
                        helm.main()
                        output = " ".join(str(c[0][0]) for c in mock_print.call_args_list if c[0])
                        self.assertIn("Administrative elevation required", output)
                        self.assertIn("automatic script elevation is barred", output)

    def test_3_uia_domain_resolution_strictly_scoped_to_hwnd_descendants(self):
        """Directive 3: get_browser_active_domain strictly scopes search to hwnd descendants (no root fallback)."""
        # When hwnd is None or not a valid window, returns None (fails closed)
        with patch.object(windows_tools, "get_foreground_window", return_value=None):
            dom_none = windows_tools.get_browser_active_domain(None)
            self.assertIsNone(dom_none)

        # Mock UIA to assert ControlFromHandle is called with hwnd and root desktop is NEVER queried
        mock_uia = MagicMock()
        mock_win_ctrl = MagicMock()
        mock_edit = MagicMock()
        mock_edit.Exists.return_value = False  # Not found under window
        mock_win_ctrl.EditControl.return_value = mock_edit
        mock_uia.ControlFromHandle.return_value = mock_win_ctrl

        with patch.dict(sys.modules, {"uiautomation": mock_uia}):
            dom = windows_tools.get_browser_active_domain(hwnd=99999)
            self.assertIsNone(dom)
            # Verify ControlFromHandle was invoked with specific hwnd
            mock_uia.ControlFromHandle.assert_called_with(99999)
            # Verify root uia.EditControl was NEVER called even when edit was not found
            mock_uia.EditControl.assert_not_called()

        # When address bar exists under window, extracts hostname correctly
        mock_edit.Exists.return_value = True
        mock_val_pat = MagicMock()
        mock_val_pat.Value = "https://legit-service.com/dashboard"
        mock_edit.GetValuePattern.return_value = mock_val_pat
        with patch.dict(sys.modules, {"uiautomation": mock_uia}):
            dom2 = windows_tools.get_browser_active_domain(hwnd=99999)
            self.assertEqual(dom2, "legit-service.com")
            mock_uia.EditControl.assert_not_called()

    def test_4_actuator_toctou_defense_blocks_foreground_window_switching(self):
        """Directive 4: SupervisorActuator re-resolves foreground window at execution time, blocking TOCTOU."""
        sup = helm_supervisor.PolicySupervisor()
        sup.state = helm_supervisor.STATE_ARMED
        actuator = helm_supervisor.SupervisorActuator(sup)

        # Mint intent token for a valid proposal in notepad.exe
        intent_token = sup.mint_intent_token("helm_agent_type", {"text": "hello"}, "worker", 1)

        # Active envelope strictly allows notepad.exe
        env = policy_envelope.PolicyEnvelope(
            envelope_id="env_test_toctou",
            allowed_process_images=["notepad.exe"],
            allowed_action_types=["helm_agent_type"],
            step_budget=10,
            keystroke_cap=500,
            expiry=time.time() + 60.0,
            taint_epoch=0
        )
        env.is_active = True
        sup.envelope = env

        # TOCTOU attack: Between proposal and actuator execution, foreground window switches to powershell.exe
        with patch.object(windows_tools, "get_foreground_window", return_value={"proc_name": "powershell.exe", "hwnd": 555}):
            with self.assertRaises(helm_supervisor.CompleteMediationBreachError) as ctx:
                actuator.execute_actuator(
                    "helm_agent_type", {"text": "hello"}, caller_id="worker", intent_token=intent_token, seq=1
                )
            self.assertIn("TOCTOU detected", str(ctx.exception))

    def test_5_exact_vk_canonicalizer_ignores_numeric_prose_and_blocks_dangerous_system_chords(self):
        """Directive 5: Free-form numeric prose does not trigger Enter/P; system hotkeys are blocked."""
        # 1. Numeric decimal strings in prose: "13" or "80"
        prose_args = {"text": ["order 13 items for 80 dollars"]}
        enter_det, p_det, vks, tokens = windows_tools.canonicalize_keyboard_arguments(prose_args)
        self.assertFalse(enter_det, "Prose text containing '13' incorrectly triggered Enter!")
        self.assertFalse(p_det, "Prose text containing '80' incorrectly triggered P/Ctrl+Alt+P!")

        # 2. Blocked system hotkey chords
        win_r_args = {"hotkey": "win+r"}
        _, _, vks_r, tokens_r = windows_tools.canonicalize_keyboard_arguments(win_r_args)
        chord_r = windows_tools.detect_blocked_system_chords(vks_r, tokens_r)
        self.assertEqual(chord_r, "Win+R")

        alt_f4_args = {"hotkey": "alt+f4"}
        _, _, vks_f4, tokens_f4 = windows_tools.canonicalize_keyboard_arguments(alt_f4_args)
        chord_f4 = windows_tools.detect_blocked_system_chords(vks_f4, tokens_f4)
        self.assertEqual(chord_f4, "Alt+F4")

        ctrl_shift_esc = {"hotkey": "ctrl+shift+esc"}
        _, _, vks_esc, tokens_esc = windows_tools.canonicalize_keyboard_arguments(ctrl_shift_esc)
        chord_esc = windows_tools.detect_blocked_system_chords(vks_esc, tokens_esc)
        self.assertEqual(chord_esc, "Ctrl+Shift+Esc")

        # 3. Policy Envelope strictly blocks dangerous system chords
        env = policy_envelope.PolicyEnvelope(
            envelope_id="env_test_chords",
            allowed_process_images=["notepad.exe"],
            allowed_action_types=["helm_agent_type"],
            step_budget=10,
            keystroke_cap=500,
            expiry=time.time() + 60.0,
            taint_epoch=0
        )
        env.is_active = True
        ok, msg, _ = env.check_boundary("helm_agent_type", {"hotkey": "win+r"}, "notepad.exe", 0)
        self.assertFalse(ok)
        self.assertIn("dangerous system hotkey chord 'Win+R'", msg)

        # 4. SupervisorActuator strictly blocks dangerous system chords
        sup = helm_supervisor.PolicySupervisor()
        sup.state = helm_supervisor.STATE_ARMED
        actuator = helm_supervisor.SupervisorActuator(sup)
        token = sup.mint_intent_token("helm_agent_type", {"hotkey": "win+r"}, "worker", 1)
        with patch.object(windows_tools, "get_foreground_window", return_value={"proc_name": "notepad.exe", "hwnd": 111}):
            with self.assertRaises(helm_supervisor.CompleteMediationBreachError) as ctx:
                actuator.execute_actuator("helm_agent_type", {"hotkey": "win+r"}, caller_id="worker", intent_token=token, seq=1)
            self.assertIn("Synthetic injection of dangerous system hotkey chord 'Win+R' is strictly prohibited", str(ctx.exception))

    def test_6_app_resets_physical_modifiers_on_wm_killfocus(self):
        """Directive 6: app.py resets tracked physical modifier keys on WM_KILLFOCUS (0x0008)."""
        from app import HelmApp
        app = HelmApp()
        app._physical_ctrl_down = True
        app._physical_alt_down = True

        # Simulate WM_KILLFOCUS (0x0008)
        WM_KILLFOCUS = 0x0008
        app.handle_keyboard_event(0, WM_KILLFOCUS, 0)

        self.assertFalse(app._physical_ctrl_down, "Physical Ctrl modifier remained stuck after WM_KILLFOCUS!")
        self.assertFalse(app._physical_alt_down, "Physical Alt modifier remained stuck after WM_KILLFOCUS!")


